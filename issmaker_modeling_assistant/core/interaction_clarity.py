"""HUD interaction policy, pure Python; no Blender / GPU imports.

All rectangles used by interaction are generated by the visible widget owners.
This module only decides policy, it never synthesizes invisible hit targets.
"""
from math import isfinite

ROTATION_KINDS = frozenset(("SURFACE_ROT", "CORNICE_ROT"))


def clean_preview_button(viewport_width, viewport_height):
    """A single recoverable button, clamped to an actual 3D View region."""
    w = float(viewport_width); h = float(viewport_height)
    if not all(isfinite(x) for x in (w, h)) or w < 48 or h < 50:
        return None
    width = min(162.0, max(42.0, w - 16.0))
    x = (w - width) * .5
    y = min(max(8.0, h * .065), h - 34.0)
    return (x, y, x + width, y + 29.0)


def in_rect(x, y, rect):
    return bool(rect and rect[0] <= x <= rect[2] and rect[1] <= y <= rect[3])


def blank_click_action(*, dropdown=False, editing_number=False, dragging=False,
                       clean_preview=False, pointer_over_ui=False):
    """Never commit geometry due to an accidental canvas click."""
    if clean_preview: return "PASS_THROUGH"
    if dragging: return "IGNORE"
    if pointer_over_ui: return "IGNORE"
    if dropdown: return "DISMISS_DROPDOWN"
    if editing_number: return "CANCEL_NUMBER"
    return "CLEAR_FOCUS"


def rotation_candidate(kind, value, *, source_valid=True, required_resource=True):
    if kind not in ROTATION_KINDS:
        return (False, "Неизвестный параметр поворота")
    try: angle = float(value)
    except (ValueError, TypeError): return (False, "Поворот должен быть числом")
    if not isfinite(angle): return (False, "Угол поворота не является конечным числом")
    if not source_valid: return (False, "Исходный Path недоступен или содержит ошибки")
    if kind == "CORNICE_ROT" and not required_resource:
        return (False, "Не назначен корректный профиль карниза")
    # Many whole revolutions are valid: never arbitrarily reject e.g. 540°.
    return (True, "")


def rotation_grid(angle_degrees, cx, cy, side=.7, extent=2):
    """World-space XY diagnostic preview grid (not a replacement mesh)."""
    import math
    angle=float(angle_degrees)
    if not math.isfinite(angle) or side<=0 or extent<1: raise ValueError("Invalid grid")
    u=(math.cos(math.radians(angle)),math.sin(math.radians(angle)))
    v=(-u[1],u[0]); lines=[]
    # Bound maximum primitive count independently from user input.
    extent=min(4,int(extent));scale=float(side)
    for k in range(-extent,extent+1):
        offset=k*scale/extent
        lines.append(((cx+v[0]*offset-u[0]*scale,cy+v[1]*offset-u[1]*scale),
                      (cx+v[0]*offset+u[0]*scale,cy+v[1]*offset+u[1]*scale)))
        lines.append(((cx+u[0]*offset-v[0]*scale,cy+u[1]*offset-v[1]*scale),
                      (cx+u[0]*offset+v[0]*scale,cy+u[1]*offset+v[1]*scale)))
    return tuple(lines)
